import type { AutoGroupColumnDef, ColDef, GetDataPath } from 'ag-grid-community';

import type { TreeStore } from '@/tree/TreeStore';
import type { TreeItem } from '@/tree/types';

/** Value shown in the "Категория" column for items that have children. */
export const CATEGORY_GROUP = 'Группа';
/** Value shown in the "Категория" column for leaf items. */
export const CATEGORY_ITEM = 'Элемент';

/**
 * A row is a "Группа" when it has at least one child, otherwise it is an
 * "Элемент".
 */
export function getCategory(store: TreeStore, item: TreeItem): string {
  return store.getChildren(item.id).length > 0 ? CATEGORY_GROUP : CATEGORY_ITEM;
}

/**
 * Column definitions other than the generated tree (group) column.
 *
 * The `rowNumber` column is pinned to the left so that it is always rendered
 * before the automatically generated group column, giving the
 * `No п\п | Наименование | Категория` layout.
 */
export function createColumnDefs(store: TreeStore): ColDef<TreeItem>[] {
  return [
    {
      headerName: 'No п\\п',
      colId: 'rowNumber',
      width: 110,
      pinned: 'left',
      sortable: false,
      filter: false,
      valueGetter: (params) => {
        const rowIndex = params.node?.rowIndex ?? null;
        return rowIndex === null ? '' : rowIndex + 1;
      },
    },
    {
      headerName: 'Категория',
      colId: 'category',
      width: 160,
      sortable: false,
      filter: false,
      valueGetter: (params) => (params.data ? getCategory(store, params.data) : ''),
    },
  ];
}

/** Configuration of the tree (group) column generated by AG Grid. */
export function createAutoGroupColumnDef(): AutoGroupColumnDef<TreeItem> {
  return {
    headerName: 'Наименование',
    field: 'label',
    flex: 1,
    minWidth: 240,
    cellRendererParams: {
      suppressCount: true,
    },
  };
}

/**
 * Builds the `getDataPath` callback required by AG Grid tree data: for every
 * item it returns the path of ids from the root down to the item itself.
 */
export function createGetDataPath(store: TreeStore): GetDataPath<TreeItem> {
  return (data) => {
    const path = store.getAllParents(data.id);
    const ids: string[] = new Array<string>(path.length);
    for (let i = path.length - 1, j = 0; i >= 0; i--, j++) {
      ids[j] = String(path[i].id);
    }
    return ids;
  };
}
